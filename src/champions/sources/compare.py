"""Fidelity checks across the saved snapshots -> sources/comparison.md (and stdout).

Run:  champions sources compare

Per source: coverage, freshness, and internal-consistency checks (each Pokémon's moves should sum to
~400%, since a set has 4 moves; items/abilities/natures/spreads to ~100%). Across sources, on the
Pokémon they share: usage-rank agreement (Spearman) and, per Pokémon, how much the move lists agree.
"""
import statistics
import sys

from . import common

SOURCES = [("munchstats", "doubles"), ("pikalytics", "doubles"), ("championslab", "doubles"), ("opgg", "singles")]
TARGET = {"moves": 400, "items": 100, "abilities": 100, "natures": 100}


def spearman(a, b):
    """Spearman rho of two {key: value} maps over shared keys (smaller value = better rank)."""
    ks = sorted(set(a) & set(b))
    if len(ks) < 3:
        return None, len(ks)

    def ranks(d):
        order = sorted(ks, key=lambda k: d[k])
        return {k: i for i, k in enumerate(order)}
    ra, rb = ranks(a), ranks(b)
    n = len(ks)
    d2 = sum((ra[k] - rb[k]) ** 2 for k in ks)
    return 1 - 6 * d2 / (n * (n * n - 1)), n


def consistency(snap):
    """{field: (median sum, min, max, n)} of per-Pokémon totals."""
    out = {}
    for f in list(TARGET) + ["spreads"]:
        sums = [sum(e[f].values()) for e in snap["pokemon"].values() if e.get(f)]
        if sums:
            out[f] = (statistics.median(sums), min(sums), max(sums), len(sums))
    return out


def curve_ratio(snap):
    """Usage values ordered by rank: (median ratio of consecutive values, spread of those ratios).
    A near-constant ratio means the numbers follow a smooth curve, not noisy real counts."""
    vals = [e["usage"] for e in sorted(snap["pokemon"].values(), key=lambda e: e.get("rank") or 0) if e.get("usage")]
    r = [b / a for a, b in zip(vals, vals[1:])]
    return (statistics.median(r), max(r) - min(r), len(vals)) if len(r) > 3 else None


def move_agreement(a, b):
    """Per shared Pokémon: top-4 move overlap (0-4) and mean |pct diff| on moves both list."""
    overlaps, diffs = [], []
    for k in set(a["pokemon"]) & set(b["pokemon"]):
        ma, mb = a["pokemon"][k].get("moves"), b["pokemon"][k].get("moves")
        if not ma or not mb:
            continue
        top = lambda m: {n for n, _ in sorted(m.items(), key=lambda kv: -kv[1])[:4]}
        overlaps.append(len(top(ma) & top(mb)))
        both = set(ma) & set(mb)
        if both:
            diffs.append(statistics.mean(abs(ma[n] - mb[n]) for n in both))
    return overlaps, diffs


def report():
    snaps = {s: common.load(s, f) for s, f in SOURCES}
    snaps = {s: v for s, v in snaps.items() if v}
    L = ["# Source comparison (generated by `champions sources compare`)", ""]
    L += ["## Coverage and consistency", "",
          "| source | format | fetched | Pokémon | as_of (first) | moves Σ (med/min/max) | items Σ | abilities Σ | natures Σ | spreads Σ |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for s, v in snaps.items():
        c = consistency(v)
        cell = lambda f: "{:.0f} / {:.0f} / {:.0f}".format(*c[f][:3]) if f in c else "–"
        asof = next((e.get("as_of") for e in v["pokemon"].values() if e.get("as_of")), "–")
        L.append(f"| {s} | {v['format']} | {v['fetched_at'][:10]} | {len(v['pokemon'])} | {asof} | "
                 f"{cell('moves')} | {cell('items')} | {cell('abilities')} | {cell('natures')} | {cell('spreads')} |")
    L += ["", "Moves should total ≈400 (four per set); items, abilities, natures ≈100; spreads ≤100 (only the top few are listed).", ""]
    L += ["## Usage curve shape", ""]
    for s, v in snaps.items():
        cr = curve_ratio(v)
        if cr:
            L.append(f"- {s}: consecutive-rank usage ratio median {cr[0]:.3f}, range {cr[1]:.3f} over {cr[2]} Pokémon")
    L += ["", "A range near 0 means usage falls on a perfectly smooth curve, which real counts do not do.", ""]
    L += ["## Rank agreement (Spearman ρ on shared Pokémon)", ""]
    ranks = {s: {k: e["rank"] for k, e in v["pokemon"].items() if e.get("rank")} for s, v in snaps.items()}
    names = list(ranks)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if ranks[a] and ranks[b]:
                rho, n = spearman(ranks[a], ranks[b])
                L.append(f"- {a} vs {b}: " + (f"ρ = {rho:.2f} (n={n})" if rho is not None else f"n={n}, too few"))
    L += ["", "## Move-list agreement (shared Pokémon)", "",
          "| pair | n | top-4 moves in common (mean of 4) | mean abs diff on shared moves (pct points) |", "|---|---|---|---|"]
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            ov, df = move_agreement(snaps[a], snaps[b])
            if ov:
                L.append(f"| {a} vs {b} | {len(ov)} | {statistics.mean(ov):.2f} | {statistics.mean(df):.1f} |")
    return "\n".join(L) + "\n"


def main(argv=None):
    text = report()
    (common.SOURCES / "comparison.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
